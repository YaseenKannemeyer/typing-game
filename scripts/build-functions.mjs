// Bundles Edge Functions (and the shared rules they import) into single files
// Deno can run: supabase/functions/<name>/index.ts → .build/<name>/index.js
import { build } from 'esbuild';

for (const name of ['award-trophies']) {
  await build({
    entryPoints: [`supabase/functions/${name}/index.ts`],
    outfile: `.build/${name}/index.js`,
    bundle: true,
    format: 'esm',
    platform: 'neutral',
    target: 'es2022',
    external: ['npm:*', 'jsr:*'],
    banner: { js: `// Generated by scripts/build-functions.mjs from supabase/functions/${name}. Do not edit.` },
  });
  console.log(`built .build/${name}/index.js`);
}
