/**
 * Checks every vehicle model in real Chrome against the anchor contract (see vehicle-measure.ts).
 *
 *   npm run check:vehicles              check (exit 1 on a mismatch)
 *   npm run check:vehicles -- --write   re-measure and rewrite VEHICLE_EXTENTS in art/vehicleAnchors.ts
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { chromeAvailable, CHROME, measureVehicleArt } from './vehicle-measure';

if (!chromeAvailable()) {
  console.error(`Chrome not found at ${CHROME}. Set CHROME_PATH.`);
  process.exit(1);
}

const report = await measureVehicleArt();
console.log(`Measured ${report.renders} renders in Chrome.`);

if (process.argv.includes('--write')) {
  const file = new URL('../client/src/art/vehicleAnchors.ts', import.meta.url);
  const source = readFileSync(file, 'utf8');
  const start = source.indexOf('// <vehicle-extents>');
  const end = source.indexOf('// </vehicle-extents>');
  if (start < 0 || end < 0) throw new Error('vehicleAnchors.ts: missing the // <vehicle-extents> markers');
  const rows = Object.entries(report.table).map(([model, e]) => `  ${model}: { rear: ${e.rear}, front: ${e.front} },`);
  const block = [
    '// <vehicle-extents> generated by scripts/check-vehicle-art.ts --write; do not edit by hand.',
    'export const VEHICLE_EXTENTS: Record<VehicleModel, VehicleExtents> = {',
    ...rows,
    '};',
    '',
  ].join('\n');
  const next = source.slice(0, start) + block + source.slice(end);
  if (next !== source) writeFileSync(file, next);
  console.log(next !== source ? 'Rewrote VEHICLE_EXTENTS in client/src/art/vehicleAnchors.ts.' : 'VEHICLE_EXTENTS already up to date.');
  report.stale = [];
}

for (const w of report.warnings) console.log(`warn  ${w}`);
for (const s of report.stale) console.log(`STALE ${s}`);
for (const p of report.problems) console.log(`FAIL  ${p}`);
const failures = report.stale.length + report.problems.length;
if (report.stale.length) console.log('\nRun `npm run check:vehicles -- --write` to update VEHICLE_EXTENTS from the drawings.');
console.log(failures ? `\n${failures} problem(s).` : '\nAll vehicle anchors match the drawn art.');
process.exit(failures ? 1 : 0);
