/**
 * Horizontal extents of each vehicle model's visible body inside the shared
 * 280-unit viewBox, so the track can anchor the *front bumper* (not the SVG
 * box) to the finish line. Everything drawn counts (body, details, plate and
 * both wheels); cosmetic effects (trails, smoke, glow, stars) do not.
 *
 * The values are measured from the real art in Chrome, so the artwork can use
 * any SVG syntax. After changing a model's drawing, run
 *   npm run check:vehicles -- --write
 * which re-measures every model and rewrites the table below.
 * vehicleAnchors.test.ts fails while the table is behind the art.
 */
import type { VehicleModel } from './vehicleArt';

export const VEHICLE_VIEWBOX_WIDTH = 280;

export interface VehicleExtents {
  /** Leftmost visible x (rear), in viewBox units. */
  rear: number;
  /** Rightmost visible x (front bumper), in viewBox units. */
  front: number;
}

// <vehicle-extents> generated by scripts/check-vehicle-art.ts --write; do not edit by hand.
export const VEHICLE_EXTENTS: Record<VehicleModel, VehicleExtents> = {
  classic: { rear: 31, front: 246 },
  formula: { rear: 30, front: 251 },
  muscle: { rear: 34, front: 245 },
  supercar: { rear: 33, front: 241 },
  hypercar: { rear: 32, front: 248 },
  drift: { rear: 29, front: 241 },
  rally: { rear: 38, front: 232 },
  monster: { rear: 37, front: 238 },
  pickup: { rear: 34, front: 237 },
  kart: { rear: 68, front: 211 },
  vintage: { rear: 38, front: 237 },
  cyber: { rear: 30, front: 244 },
  police: { rear: 34, front: 240 },
  taxi: { rear: 35, front: 238 },
  rocket: { rear: 42, front: 249 },
};
// </vehicle-extents>

export function vehicleExtents(model: VehicleModel): VehicleExtents {
  return VEHICLE_EXTENTS[model];
}

/**
 * CSS `left` for a car of width `--car-w` so that at progress 0 its rear sits
 * on the start line and at progress 1 its front bumper sits exactly on the
 * finish line, moving linearly in between.
 */
export function laneLeft(model: VehicleModel, progress: number): string {
  const p = Math.min(1, Math.max(0, progress));
  const { rear, front } = vehicleExtents(model);
  const r = rear / VEHICLE_VIEWBOX_WIDTH;
  const f = front / VEHICLE_VIEWBOX_WIDTH;
  const k = (1 - p) * (f - r) - f;
  return `calc(${(p * 100).toFixed(3)}% + ${k.toFixed(4)} * var(--car-w))`;
}
